export const hasTechIcon = (name: string) => name.toLowerCase() in ICONS;

/** Tech logo for a skill name; renders a small dot when no logo exists. */
export function TechIcon({ name, className }: { name: string; className?: string }) {
  const Icon = ICONS[name.toLowerCase()];
  if (Icon) return <Icon aria-hidden className={cn('size-5 shrink-0', className)} />;
  return (
    <span aria-hidden className={cn('grid size-5 shrink-0 place-items-center', className)}>
      <span className="size-1.5 rounded-full bg-current opacity-60" />
    </span>
  );
}

